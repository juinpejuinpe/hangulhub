  async setupTopikPanel(ctx) {
    const errBox = $("#topik-error");
    const showErr = (msg) => {
      if (errBox) errBox.innerHTML = `<div class="error-banner">${esc(msg)}</div>`;
    };
    const yearSel = $("#topik-year");
    const sessionSel = $("#topik-session");
    const importBtn = $("#topik-import");
    try {
      const { papers } = await API.get("/api/topik/papers");
      if (!papers || !papers.length) {
        showErr("The official site returned no papers right now. Try again in a moment.");
        return;
      }
      yearSel.innerHTML = papers.map((p, i) =>
        `<option value="${esc(p.year)}" ${i === 0 ? "selected" : ""}>
           ${esc(p.year)}</option>`).join("");
      const fillSessions = () => {
        const year = yearSel.value;
        const row = papers.find((p) => p.year === year) || papers[0];
        sessionSel.innerHTML = (row.sessions || []).map((s) =>
          `<option value="${esc(s)}">${row.sessions.length > 1
            ? `session ${esc(s)}` : "this session"}</option>`).join("");
        importBtn.disabled = false;
      };
      yearSel.onchange = fillSessions;
      fillSessions();
    } catch (err) {
      showErr(`Could not load the official paper list: ${err.message}`);
      return;
    }
    importBtn.onclick = async () => {
      const year = yearSel.value;
      const no = sessionSel.value;
      const grade = $("#topik-grade").value;
      importBtn.disabled = true;
      const badge = UI.busy(`Downloading official TOPIK paper…`);
      try {
        const result = await API.post("/api/topik/import", {
          courseId: ctx.course.id,
          chapterId: ctx.chapter ? ctx.chapter.id : null,
          no,
          grade,
          year,
        });
        UI.toast(`Imported “${result.title}” — ready to convert.`);
        await refreshAll();
        render();
      } catch (err) {
        handleApiError(err, "Could not import the paper.");
      } finally {
        badge();
        importBtn.disabled = false;
      }
    };
  },

